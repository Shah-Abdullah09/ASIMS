"""A4 letters on the university letterhead, shared by the award letter and the internship letters.

A letter is written from the top of the page down: each method draws at the current position and moves it on.
The signature block is left blank for a manual signature and the office stamp (no e-signature)."""
from io import BytesIO
from pathlib import Path

from django.utils import timezone
from reportlab.lib.colors import HexColor
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib.utils import ImageReader, simpleSplit
from reportlab.pdfgen import canvas

LOGO = Path(__file__).parent / 'assets' / 'au-logo.png'
BLUE = HexColor('#1A6FA0')
TEXT = HexColor('#1A1A1A')
GREY = HexColor('#555555')
UNIVERSITY = 'Air University Multan'


class Letter:
    def __init__(self, title, office='Placement Office'):
        self.office = office
        self.buffer = BytesIO()
        self.pdf = canvas.Canvas(self.buffer, pagesize=A4, pageCompression=1)
        self.pdf.setTitle(title)
        self.pdf.setAuthor(f'{office}, {UNIVERSITY}')
        self.page_w, page_h = A4
        self.left, self.right = 25 * mm, self.page_w - 25 * mm
        self.width = self.right - self.left
        self.y = page_h - 20 * mm

    def space(self, amount):
        self.y -= amount

    def letterhead(self, reference, issued_on):
        """Logo, university and office, a blue rule, then the reference and date."""
        pdf, top, logo_h = self.pdf, self.y, 22 * mm
        if LOGO.exists():
            logo = ImageReader(str(LOGO))
            iw, ih = logo.getSize()
            pdf.drawImage(logo, self.left, top - logo_h, width=logo_h * iw / ih, height=logo_h, mask='auto')
        pdf.setFillColor(BLUE)
        pdf.setFont('Helvetica-Bold', 16)
        pdf.drawRightString(self.right, top - 8 * mm, UNIVERSITY.upper())
        pdf.setFont('Helvetica', 11)
        pdf.drawRightString(self.right, top - 14 * mm, self.office)
        pdf.setStrokeColor(BLUE)
        pdf.setLineWidth(1.2)
        pdf.line(self.left, top - logo_h - 4 * mm, self.right, top - logo_h - 4 * mm)

        pdf.setFillColor(TEXT)
        self.y = top - logo_h - 14 * mm
        pdf.setFont('Helvetica', 10)
        pdf.drawString(self.left, self.y, f'Ref: {reference}')
        pdf.drawRightString(self.right, self.y, f'Date: {issued_on:%d %B %Y}')

    def title(self, text, subtitle=''):
        self.pdf.setFont('Helvetica-Bold', 13)
        self.pdf.drawCentredString(self.page_w / 2, self.y, text)
        if subtitle:
            self.pdf.setFont('Helvetica', 11)
            self.pdf.drawCentredString(self.page_w / 2, self.y - 6 * mm, subtitle)

    def details(self, rows):
        """Label: value lines, e.g. the student's name and registration ID."""
        for label, value in rows:
            self.pdf.setFont('Helvetica-Bold', 11)
            self.pdf.drawString(self.left, self.y, f'{label}:')
            self.pdf.setFont('Helvetica', 11)
            self.pdf.drawString(self.left + 45 * mm, self.y, value)
            self.y -= 6.5 * mm

    def paragraph(self, text, indent=0, font='Helvetica', size=11, leading=15):
        for line in simpleSplit(text, font, size, self.width - indent):
            self.pdf.setFont(font, size)
            self.pdf.drawString(self.left + indent, self.y, line)
            self.y -= leading

    def heading(self, text):
        self.pdf.setFont('Helvetica-Bold', 11)
        self.pdf.drawString(self.left, self.y, text)

    def numbered(self, items):
        for number, text in enumerate(items, 1):
            self.pdf.setFont('Helvetica', 11)
            self.pdf.drawString(self.left, self.y, f'{number}.')
            self.paragraph(text, indent=6 * mm)
            self.y -= 3

    def signature(self):
        """A line to sign on and the office name, with room for the stamp."""
        pdf, x = self.pdf, self.right - 70 * mm
        pdf.line(x, self.y, self.right, self.y)
        pdf.setFont('Helvetica', 10)
        pdf.drawString(x, self.y - 5 * mm, self.office)
        pdf.drawString(x, self.y - 10 * mm, UNIVERSITY)
        pdf.drawString(self.left, self.y - 5 * mm, 'Office stamp:')

    def finish(self, note):
        """The footer (generation time and `note`) and the finished PDF as bytes."""
        self.pdf.setFont('Helvetica', 8)
        self.pdf.setFillColor(GREY)
        self.pdf.drawCentredString(self.page_w / 2, 12 * mm,
                                   f'Generated by ASIMS on {timezone.localtime():%d %b %Y %H:%M}. {note}')
        self.pdf.showPage()
        self.pdf.save()
        return self.buffer.getvalue()
